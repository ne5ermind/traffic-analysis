"""SQLite storage; each process opens its own connection and WAL supports readers."""
import json
import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path

ROOT = Path(os.environ.get("INNOVA_DATA", Path(__file__).resolve().parents[1] / "data"))
ROOT.mkdir(parents=True, exist_ok=True)
DB = ROOT / "innova.db"
PROJECT_DATA = Path(__file__).resolve().parents[1] / "data"


def resolve_data_path(value):
    """Resolve a path stored relative to ROOT, with a legacy Docker-path fallback.

    Older databases stored absolute paths such as ``/srv/innova/data/uploads/...``.
    When the same data directory is opened locally that prefix is no longer valid,
    but the generated upload filename is still unique.  Falling back by basename
    inside ROOT/uploads keeps those databases usable without trusting an arbitrary
    external path.
    """
    saved = Path(value)
    if saved.is_absolute():
        if saved.is_file():
            return saved
        candidate = ROOT / "uploads" / saved.name
        return candidate if candidate.is_file() else saved

    root = ROOT.resolve()
    candidate = (ROOT / saved).resolve()
    try:
        candidate.relative_to(root)
    except ValueError:
        # Database paths are generated by this application, but keep a corrupted
        # relative value from escaping the configured data directory.
        candidate = ROOT / "uploads" / saved.name
    if candidate.is_file():
        return candidate
    fallback = ROOT / "uploads" / saved.name
    return fallback if fallback.is_file() else candidate


def portable_data_path(value):
    """Return a ROOT-relative representation when the path belongs to app data."""
    path = Path(value).resolve()
    try:
        return path.relative_to(ROOT.resolve()).as_posix()
    except ValueError:
        return str(path)


def resolve_model_path(value):
    """Resolve current and legacy model references without trusting their prefix."""
    saved = Path(value)
    roots = tuple(dict.fromkeys(((ROOT / "models").resolve(),
                                (PROJECT_DATA / "models").resolve())))

    def allowed(candidate):
        candidate = candidate.resolve()
        return (candidate.suffix.lower() == ".pt" and
                any(candidate.is_relative_to(root) for root in roots))

    if saved.is_absolute() and saved.is_file() and allowed(saved):
        return saved.resolve()
    if not saved.is_absolute():
        for base in (ROOT, PROJECT_DATA, Path(__file__).resolve().parents[1]):
            candidate = (base / saved).resolve()
            if candidate.is_file() and allowed(candidate):
                return candidate
    # Docker and local checkouts have different absolute prefixes.  Models are
    # deliberately restricted to the two application model directories.
    for directory in roots:
        candidate = directory / saved.name
        if candidate.is_file() and allowed(candidate):
            return candidate
    # Return a safe expected location so the worker can produce a useful
    # missing-weight error without ever opening an arbitrary absolute path.
    return roots[0] / saved.name


def portable_model_path(value):
    """Store a flat model name independently of the Docker/local project path."""
    return f"models/{Path(value).name}"


@contextmanager
def connection():
    db = sqlite3.connect(DB, timeout=30)
    db.row_factory = sqlite3.Row
    db.execute("PRAGMA foreign_keys=ON")
    db.execute("PRAGMA journal_mode=WAL")
    try:
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


def init():
    with connection() as db:
        db.executescript("""
        CREATE TABLE IF NOT EXISTS videos(
          id TEXT PRIMARY KEY, name TEXT NOT NULL, path TEXT NOT NULL,
          width INTEGER, height INTEGER, duration REAL, fps REAL, created_at TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS scenes(
          id TEXT PRIMARY KEY, video_id TEXT NOT NULL REFERENCES videos(id),
          name TEXT NOT NULL, geometry TEXT NOT NULL, created_at TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS runs(
          id TEXT PRIMARY KEY, scene_id TEXT NOT NULL REFERENCES scenes(id),
          video_id TEXT NOT NULL REFERENCES videos(id), geometry TEXT NOT NULL,
          status TEXT NOT NULL, progress REAL DEFAULT 0, message TEXT DEFAULT '',
          model TEXT NOT NULL, tracker TEXT NOT NULL, created_at TEXT NOT NULL,
          started_at TEXT, finished_at TEXT, heartbeat TEXT, cancelled INTEGER DEFAULT 0);
        CREATE TABLE IF NOT EXISTS events(
          id TEXT PRIMARY KEY, run_id TEXT NOT NULL REFERENCES runs(id), tracker_id INTEGER,
          category TEXT NOT NULL, from_direction TEXT NOT NULL, to_direction TEXT NOT NULL,
          time_s REAL NOT NULL, start_s REAL, confidence REAL, status TEXT NOT NULL,
          origin TEXT NOT NULL, version INTEGER NOT NULL DEFAULT 1, details TEXT NOT NULL,
          created_at TEXT NOT NULL, updated_at TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS revisions(
          id INTEGER PRIMARY KEY AUTOINCREMENT, event_id TEXT NOT NULL,
          old_value TEXT, new_value TEXT NOT NULL, reason TEXT, created_at TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS ground_truth(
          id TEXT PRIMARY KEY, video_id TEXT NOT NULL REFERENCES videos(id),
          name TEXT NOT NULL, format TEXT NOT NULL, payload TEXT NOT NULL,
          created_at TEXT NOT NULL);
        CREATE UNIQUE INDEX IF NOT EXISTS event_identity ON events(run_id,tracker_id,origin,time_s);
        CREATE INDEX IF NOT EXISTS event_run_time ON events(run_id,time_s);
        CREATE INDEX IF NOT EXISTS run_state ON runs(status,created_at);
        """)
        # Normalize resolvable upload paths lazily.  Missing legacy paths are left
        # untouched so a later mount can still restore them.
        for video in db.execute("SELECT id,path FROM videos").fetchall():
            resolved = resolve_data_path(video["path"])
            if resolved.is_file():
                portable = portable_data_path(resolved)
                if portable != video["path"]:
                    db.execute("UPDATE videos SET path=? WHERE id=?", (portable, video["id"]))
        for run in db.execute("SELECT id,model FROM runs").fetchall():
            saved = run["model"]
            try:
                configuration = json.loads(saved) if saved.startswith("{") else None
            except (TypeError, json.JSONDecodeError):
                configuration = None
            if isinstance(configuration, dict) and isinstance(configuration.get("models"), list):
                models = []
                complete = True
                for model in configuration["models"]:
                    resolved = resolve_model_path(model)
                    complete &= resolved.is_file()
                    models.append(portable_model_path(resolved) if resolved.is_file() else model)
                if complete and models != configuration["models"]:
                    configuration["models"] = models
                    db.execute("UPDATE runs SET model=? WHERE id=?",
                               (json.dumps(configuration), run["id"]))
            elif configuration is None:
                resolved = resolve_model_path(saved)
                if resolved.is_file():
                    portable = portable_model_path(resolved)
                    if portable != saved:
                        db.execute("UPDATE runs SET model=? WHERE id=?", (portable, run["id"]))


def rows(db, query, params=()):
    return [dict(row) for row in db.execute(query, params).fetchall()]


def parse_event(row):
    row = dict(row)
    row["details"] = json.loads(row["details"])
    return row
